"""Configuration: dataclasses, YAML (de)serialization, routing and config hashing.

``configs/groups.yaml`` is generated by ``python -m captcha.inspect_data
--report --write-config`` and then meant to be hand-edited (charset mode, review
flags, per-group overrides). Every checkpoint embeds the ``config_hash`` of the
group it was trained from, and ``predict`` refuses to load a checkpoint whose
charset disagrees with the config -- a checkpoint without its charset and width
is meaningless.
"""

from __future__ import annotations

import dataclasses
import hashlib
import json
from dataclasses import dataclass, field
from pathlib import Path
from typing import Any, Dict, List, Optional, Sequence, Tuple

import yaml

from . import HEIGHT

Size = Tuple[int, int]


def group_id_for(size: Size) -> str:
    """Stable group id from an image size, e.g. ``(180, 64) -> 'g_180x64'``."""
    return f"g_{size[0]}x{size[1]}"


# --------------------------------------------------------------------------- #
# sub-configs
# --------------------------------------------------------------------------- #
@dataclass
class PreprocCfg:
    height: int = HEIGHT
    in_channels: int = 1
    # Per-image polarity canonicalization: measure the median of the 2px border
    # ring and invert when it is dark. 5 of the 14 groups have dark backgrounds
    # (ring 0-87) vs the light ones (149-255); without this step those 5 train on
    # inverted images relative to the rest.
    polarity_normalize: bool = True
    border_px: int = 2
    # Per-group noise gate. Some sources draw their distractor lines *brighter*
    # than the glyphs (g_600x120: text 16-79, lines 96-111 on a black ring), so
    # after polarity canonicalization the lines end up as the only high-contrast
    # structure and the model has nothing else to latch onto. Pixels above this
    # value are pushed back to the border-ring level before the stretch. None
    # keeps the old behaviour, which is what every other group wants -- a light
    # background would be erased by this.
    clip_above: Optional[float] = None
    # Percentile contrast stretch (not min/max: the styles contain isolated
    # speckle that would destroy a min/max stretch).
    stretch_lo: float = 2.0
    stretch_hi: float = 98.0
    # Optional CLAHE for low-contrast groups. Off by default; global histogram
    # equalization is deliberately NOT used (amplifies speckle, can invert
    # polarity locally).
    clahe: bool = False
    clahe_clip: float = 2.0
    clahe_grid: int = 4


@dataclass
class AugCfg:
    """Training-time augmentation. Every entry here is CTC-safe.

    Horizontal flip is deliberately absent (and asserted against at runtime): it
    mirrors glyphs *and* reverses the left-to-right ordering CTC assumes, which
    corrupts both label and alignment. Same for large rotations/shear, vertical
    flip, RandomResizedCrop (crops characters the label still claims), color
    jitter (meaningless after grayscale), random polarity inversion (conflicts
    with the canonicalization above) and Mixup/CutMix (incompatible with
    sequence labels).
    """

    enabled: bool = True
    rotate_deg: float = 3.0
    shear: float = 0.05
    scale_lo: float = 0.95
    scale_hi: float = 1.05
    translate: float = 0.02
    width_stretch: float = 0.05
    bright_lo: float = 0.8
    bright_hi: float = 1.2
    noise_sigma: float = 0.05
    blur_p: float = 0.15
    # Drawing extra thin crossing lines is the single most valuable augmentation
    # for this dataset: about half the groups have crossing-line interference.
    line_p: float = 0.15
    cutout_p: float = 0.2
    cutout_max_w: int = 8
    cutout_max_h: int = 12


@dataclass
class TrainCfg:
    epochs: int = 60
    batch_size: int = 64
    lr: float = 1e-3
    weight_decay: float = 1e-4
    grad_clip: float = 5.0
    # Early stopping is monitored on val exact-match, not loss.
    patience: int = 8
    min_delta: float = 0.001
    lr_factor: float = 0.5
    lr_patience: int = 3
    min_lr: float = 1e-5
    dropout: float = 0.1
    hidden: int = 256
    rnn_layers: int = 2
    val_frac: float = 0.1
    test_frac: float = 0.1
    seed: int = 1337
    num_workers: int = 4
    # 0 means "no limit". Used by the smoke-test gates.
    limit: int = 0
    max_steps: int = 0


@dataclass
class GroupCfg:
    """One captcha source. A merge is expressed by listing several sizes here,
    which also means the dataset must bucket by width (see dataset.py)."""

    group_id: str
    sizes: List[Size] = field(default_factory=list)
    charset: str = ""
    charset_mode: str = "core"          # core | full | map
    min_freq: float = 0.005
    review: bool = False                # forced human decision (drop > 10%)
    width: int = 0                      # canonical preprocessed width
    height: int = HEIGHT
    in_channels: int = 1
    clahe: bool = False
    clip_above: Optional[float] = None  # see PreprocCfg.clip_above
    note: str = ""

    @property
    def is_merged(self) -> bool:
        return len(self.sizes) > 1

    @property
    def num_classes(self) -> int:
        return len(self.charset) + 1    # +1 for the CTC blank

    def charset_list(self) -> List[str]:
        return list(self.charset)

    def require_unmerged(self, where: str) -> None:
        """Refuse a merged group in the fixed-width paths.

        ``dataset.py`` buckets by exact width, so a merge is genuinely supported
        while *building batches* -- that is what makes the knob worth keeping.
        But everything downstream of the batch assumes one canonical width per
        group: the ``T >= 2L+1`` check is computed from ``group.width``, the
        inference path resizes every image to ``group.width``, and the ONNX graph
        is exported with static shapes. A merged group would therefore pass
        validation against the wrong timestep count and squash every source size
        to the first size's width -- silently wrong rather than obviously broken.
        """
        if self.is_merged:
            raise NotImplementedError(
                f"{where}: group {self.group_id!r} merges {len(self.sizes)} sizes "
                f"({self.sizes}), but this path assumes a single canonical width "
                f"per group. Only batch-building supports a merge today; the "
                f"timestep check, inference and ONNX export do not. Either keep "
                f"the sizes as separate groups, or finish merge support before "
                f"pointing this at one.")

    def to_dict(self) -> Dict[str, Any]:
        d = dataclasses.asdict(self)
        d["sizes"] = [list(s) for s in self.sizes]
        return d

    @staticmethod
    def from_dict(d: Dict[str, Any]) -> "GroupCfg":
        d = dict(d)
        d["sizes"] = [tuple(s) for s in d.get("sizes", [])]
        known = {f.name for f in dataclasses.fields(GroupCfg)}
        return GroupCfg(**{k: v for k, v in d.items() if k in known})


@dataclass
class Config:
    data_dir: str = "pass"
    preproc: PreprocCfg = field(default_factory=PreprocCfg)
    aug: AugCfg = field(default_factory=AugCfg)
    train: TrainCfg = field(default_factory=TrainCfg)
    groups: List[GroupCfg] = field(default_factory=list)

    # ---------------------------------------------------------------- lookups
    def by_id(self, group_id: str) -> GroupCfg:
        for g in self.groups:
            if g.group_id == group_id:
                return g
        known = ", ".join(g.group_id for g in self.groups)
        raise KeyError(f"unknown group {group_id!r}; known groups: {known}")

    def size_router(self) -> Dict[Size, GroupCfg]:
        """Exact ``(W, H) -> group`` routing table. Size is a perfect
        discriminator across this dataset, so routing is exact."""
        router: Dict[Size, GroupCfg] = {}
        for g in self.groups:
            for s in g.sizes:
                router[(int(s[0]), int(s[1]))] = g
        return router

    def nearest_group(self, size: Size) -> Tuple[GroupCfg, float]:
        """Fallback for an unseen size: score by aspect + absolute height.

        Aspect dominates because these generators differ most in glyph aspect;
        height is a weaker secondary signal. Returns ``(group, score)``, lower is
        closer.
        """
        import math

        w, h = size
        best: Optional[GroupCfg] = None
        best_score = float("inf")
        for g in self.groups:
            gw, gh = g.sizes[0]
            score = (abs(math.log(w / h) - math.log(gw / gh))
                     + 0.5 * abs(math.log(h) - math.log(gh)))
            if score < best_score:
                best_score, best = score, g
        assert best is not None, "config has no groups"
        return best, best_score

    # ----------------------------------------------------------------- hashes
    def preproc_for(self, group: GroupCfg) -> PreprocCfg:
        """Preprocessing for one group: the global config plus its own overrides.

        ``height`` must come from the group, because the model is built from
        ``group.height``: letting the global height win instead produces a CNN
        whose projection expects a different feature size than the data carries,
        which only surfaces as a matmul shape error on the first batch.
        """
        overrides = {}
        if group.clip_above is not None:
            overrides["clip_above"] = group.clip_above
        if group.height and group.height != self.preproc.height:
            overrides["height"] = group.height
        if not overrides:
            return self.preproc
        return dataclasses.replace(self.preproc, **overrides)

    def hash_for(self, group: GroupCfg) -> str:
        """Hash of everything that makes a checkpoint interpretable."""
        payload = {
            "group": group.to_dict(),
            "preproc": dataclasses.asdict(self.preproc),
            "model": {"hidden": self.train.hidden, "rnn_layers": self.train.rnn_layers},
            "version": 1,
        }
        blob = json.dumps(payload, sort_keys=True, default=str).encode()
        return hashlib.sha1(blob).hexdigest()[:16]

    # -------------------------------------------------------------- serialize
    def to_dict(self) -> Dict[str, Any]:
        return {
            "data_dir": self.data_dir,
            "preproc": dataclasses.asdict(self.preproc),
            "aug": dataclasses.asdict(self.aug),
            "train": dataclasses.asdict(self.train),
            "groups": [g.to_dict() for g in self.groups],
        }

    def save(self, path: Path) -> None:
        path = Path(path)
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_text(
            yaml.safe_dump(self.to_dict(), sort_keys=False, allow_unicode=True),
            encoding="utf-8",
        )

    @staticmethod
    def load(path: Path) -> "Config":
        raw = yaml.safe_load(Path(path).read_text(encoding="utf-8")) or {}
        return Config(
            data_dir=raw.get("data_dir", "pass"),
            preproc=PreprocCfg(**{k: v for k, v in (raw.get("preproc") or {}).items()
                                  if k in {f.name for f in dataclasses.fields(PreprocCfg)}}),
            aug=AugCfg(**{k: v for k, v in (raw.get("aug") or {}).items()
                          if k in {f.name for f in dataclasses.fields(AugCfg)}}),
            train=TrainCfg(**{k: v for k, v in (raw.get("train") or {}).items()
                              if k in {f.name for f in dataclasses.fields(TrainCfg)}}),
            groups=[GroupCfg.from_dict(g) for g in (raw.get("groups") or [])],
        )


def default_config_path(project_root: Path) -> Path:
    return Path(project_root) / "configs" / "groups.yaml"


def runs_dir(project_root: Path, group_id: str) -> Path:
    return Path(project_root) / "runs" / group_id


def build_groups(sizes: Sequence[Size], charset_by_group: Dict[str, str],
                 widths_by_group: Dict[str, int], modes: Optional[Dict[str, str]] = None,
                 review: Optional[Dict[str, bool]] = None,
                 notes: Optional[Dict[str, str]] = None,
                 preproc: Optional[PreprocCfg] = None) -> List[GroupCfg]:
    """One group per size. ``merge`` in the YAML is done by hand later."""
    preproc = preproc or PreprocCfg()
    modes = modes or {}
    review = review or {}
    notes = notes or {}
    out: List[GroupCfg] = []
    for size in sizes:
        gid = group_id_for(size)
        out.append(GroupCfg(
            group_id=gid,
            sizes=[tuple(size)],
            charset=charset_by_group.get(gid, ""),
            charset_mode=modes.get(gid, "core"),
            review=review.get(gid, False),
            width=int(widths_by_group.get(gid, 0)),
            height=preproc.height,
            in_channels=preproc.in_channels,
            note=notes.get(gid, ""),
        ))
    return out
